from pymodbus.client import ModbusSerialClient
import time

client = ModbusSerialClient(method='rtu', port='/dev/ttyACM0', baudrate=9600)

try:
    getCurrent = client.read_holding_registers(3000, 8, slave = 2)
    time.sleep(0.1)
    getVoltage = client.read_holding_registers(3020, 14, slave = 2)
    time.sleep(0.1)
    getPower = client.read_holding_registers(3054, 30, slave = 2)
    time.sleep(0.1)
    getFreq = client.read_holding_registers(3110, 2, slave = 2)
    time.sleep(0.1)
    getWh = client.read_holding_registers(3204, 4, slave = 2)
    time.sleep(0.1)
    getVARh = client.read_holding_registers(3220, 4, slave = 2)
    time.sleep(0.1)
    getTHDi = client.read_holding_registers(21300, 6, slave = 2)
    time.sleep(0.1)
    getTHDv = client.read_holding_registers(21330, 6, slave = 2)
    time.sleep(0.1)
    getHarmVA = client.read_holding_registers(22876, 86, slave = 2)
    time.sleep(0.1)
    getHarmVB = client.read_holding_registers(23264, 86, slave = 2)
    time.sleep(0.1)
    getHarmVC = client.read_holding_registers(23652, 86, slave = 2)
    time.sleep(0.1)
    getHarmIA = client.read_holding_registers(24428, 86, slave = 2)
    time.sleep(0.1)
    getHarmIB = client.read_holding_registers(24816, 86, slave = 2)
    time.sleep(0.1)
    getHarmIC = client.read_holding_registers(25204, 86, slave = 2)
except Exception as e:
    print("Error cak:", e)

print("PM2100 Test")
print("Current     : " + str(getCurrent.registers))
print("Voltage     : " + str(getVoltage.registers))
print("Power       : " + str(getPower.registers))
print("Frequency   : " + str(getFreq.registers))
print("kWh         : " + str(getWh.registers))
print("kVARh       : " + str(getVARh.registers))
print("THD Current : " + str(getTHDi.registers))
print("THD Voltage : " + str(getTHDv.registers))
print("Harmonic VA : " + str(getHarmVA.registers))
print("Harmonic VB : " + str(getHarmVB.registers))
print("Harmonic VC : " + str(getHarmVC.registers))
print("Harmonic IA : " + str(getHarmIA.registers))
print("Harmonic IB : " + str(getHarmIB.registers))
print("Harmonic IC : " + str(getHarmIC.registers))

client.close()